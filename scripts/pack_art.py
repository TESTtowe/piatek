#!/usr/bin/env python3
"""Losslessly package the provided PNG into <=1024px Roblox EditableImage tiles.

This is transport encoding only: no retouching, resizing or visual alteration.
Optional authoring dependencies: Pillow and zstandard. Builds use committed data.
"""
import base64
import hashlib
import json
from pathlib import Path
from PIL import Image
import zstandard

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = ROOT / 'assets/menu-corridor.png'
    image = Image.open(source).convert('RGBA')
    width, height = image.size
    rows = ['-- Generated by scripts/pack_art.py; pixels are lossless RGBA, Zstandard + Base64.',
            'return {', f'    width = {width}, height = {height},', '    tiles = {']
    manifest = {'source': 'menu-corridor.png', 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                'width': width, 'height': height, 'decodedBytes': width * height * 4, 'tiles': []}
    compressor = zstandard.ZstdCompressor(level=14, write_content_size=True)
    step_x, step_y = (width + 1)//2, (height + 1)//2
    for y in range(0, height, step_y):
        for x in range(0, width, step_x):
            w, h = min(step_x, width-x), min(step_y, height-y)
            assert w <= 1024 and h <= 1024
            pixels = image.crop((x, y, x+w, y+h)).tobytes()
            compressed = compressor.compress(pixels)
            assert zstandard.ZstdDecompressor().decompress(compressed) == pixels
            encoded = base64.b64encode(compressed).decode()
            rows += [f'        {{ x = {x}, y = {y}, width = {w}, height = {h}, data =', '[=[' + encoded + ']=] },']
            manifest['tiles'].append({'x': x, 'y': y, 'width': w, 'height': h,
                                      'rgbaSha256': hashlib.sha256(pixels).hexdigest(), 'compressedSha256': hashlib.sha256(compressed).hexdigest(), 'compressedBytes': len(compressed)})
    rows += ['    },', '}', '']
    (ROOT/'src/client/MenuArt.luau').write_text('\n'.join(rows))
    (ROOT/'assets/manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(f'Packed {width}x{height} pixels in {len(manifest["tiles"])} tiles without resampling')


if __name__=='__main__': main()
